// 硬编码以避免存根中的相对导入问题
const ASK_USER_QUESTION_TOOL_NAME = 'AskUserQuestion'

export const EXIT_PLAN_MODE_V2_TOOL_PROMPT = `当你处于计划模式、且已把计划写入计划文件、准备好请求用户批准时，使用此工具。

## 此工具的工作方式
- 你应当已经把计划写入计划模式系统消息所指定的计划文件
- 此工具不以计划内容为参数——它会从你写入的文件读取计划
- 此工具只是发出信号，表明你已完成规划，等待用户审阅并批准
- 用户审阅时会看到你的计划文件内容

## 何时使用此工具
重要：仅当任务需要为写代码的步骤做实施规划时才使用此工具。对于纯研究类任务（收集信息、搜索文件、读取文件或一般性地尝试理解代码库），不要使用此工具。

## 使用此工具之前
确保你的计划完整且无歧义：
- 若你对需求或方案有未解决的问题，请先用 ${ASK_USER_QUESTION_TOOL_NAME}（在较早阶段）
- 计划敲定后，使用此工具请求批准

**重要：** 不要用 ${ASK_USER_QUESTION_TOOL_NAME} 来问“这个计划行吗？”或“我应该继续吗？”——这正是此工具要做的事。ExitPlanMode 本身就会请求用户批准你的计划。

## 示例

1. 初始任务：“搜索并理解代码库中 vim 模式的实现”——不要使用退出计划模式工具，因为你并没有在规划某任务的实施步骤。
2. 初始任务：“帮我为 vim 实现 yank 模式”——在完成该任务实施步骤的规划后，使用退出计划模式工具。
3. 初始任务：“新增一个处理用户认证的功能”——若对认证方式（OAuth、JWT 等）不确定，先用 ${ASK_USER_QUESTION_TOOL_NAME}，澄清方案后再使用退出计划模式工具。
`
